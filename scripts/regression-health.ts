declare const require: any;
const assert = require('assert').strict;
const fs = require('fs');
const path = require('path');
import { calculateOfflineReward, calculateOfflineSeconds, MAX_OFFLINE_SECONDS } from '../src/engine/offlineEarnings';
import { advanceGameTime, createInitialGameTime } from '../src/engine/gameTimeEngine';
import { DEFAULT_BUSINESSES, simulateBusinessTick } from '../src/engine/businessSimulation';
import { DEFAULT_PROGRESSION, hydrateDailyProgress } from '../src/types/progression';
import { businessValuation, createIPOListing, getIPOEligibility } from '../src/engine/ipoEngine';

const root = process.cwd();
const read = (file: string) => fs.readFileSync(path.join(root, file), 'utf8');
const app = read('App.tsx');
const gameContext = read('src/context/GameContext.tsx');
const businessScreen = read('src/screens/BusinessScreen.tsx');
const registration = read('src/components/modals/BusinessRegistrationModal.tsx');
const network = read('src/context/NetworkContext.tsx');

assert.match(app, /AsyncStorage\.getItem\(SAVE\)/, 'save/load: AsyncStorage load path missing');
assert.match(app, /JSON\.parse\(raw\)/, 'save/load: JSON parse path missing');
assert.match(app, /latestState\.current/, 'save/load: latest state snapshot missing');
assert.match(gameContext, /hydrated/, 'save/load: business hydration gate missing');
assert.equal(calculateOfflineSeconds(1000 + MAX_OFFLINE_SECONDS * 1000 * 4, 1000), MAX_OFFLINE_SECONDS, 'offline earnings: 24-hour cap failed');
assert.equal(calculateOfflineSeconds(1000, 1000 + 2 * 60 * 60 * 1000), 0, 'offline earnings: rollback failed');
assert.equal(calculateOfflineReward(3600001, 1, 3600), 3600, 'offline earnings: hourly payout failed');
assert.equal(calculateOfflineReward(3600001, 1, 3600, true), 0, 'offline earnings: tamper guard failed');
const clock = createInitialGameTime(10_000);
assert.equal(advanceGameTime(clock, 11_000).gameTimestamp - clock.gameTimestamp, 300_000, 'clock: five simulated minutes per real second failed');
const retail = { id: 'regression-retail', name: 'Regression Retail', sector: 'Retail' as const, isUnlocked: true, unlockNetWorthRequired: 0, isAcquired: true, acquisitionCost: 2500, legalStatus: 'Licensed_Legal' as const, policeHeat: 0, stability: 92, hourlyNetProfit: 0, stockUnits: 10, maxStockCapacity: 2500, pricingTier: 'Standard' as const, hasSecurity: false, hasManager: false, unitWholesaleCost: 2, monthlyRent: 800, monthlyPayroll: 1200 };
const retailTick = simulateBusinessTick([retail], 2);
assert.equal((retailTick.businesses[0] as typeof retail).stockUnits, 5, 'retail: stock deduction failed');
assert.equal(retailTick.cashDelta, 6.15, 'retail: COGS/tax settlement failed');
assert.equal(simulateBusinessTick([{ ...retail, stockUnits: 0 }], 2).cashDelta, 0, 'retail: empty inventory payout failed');
assert.equal(DEFAULT_BUSINESSES.length, 10, 'businesses: ten-sector catalog missing');
const expansion = DEFAULT_BUSINESSES.find(item => item.sector === 'Energy')!;
assert.equal(simulateBusinessTick([{ ...expansion, isAcquired: true }], 2).businesses[0].isAcquired, true, 'businesses: expansion sector tick failed');
assert.match(businessScreen, /Math\.max\(0, value \+ result\.cashDelta\)/, 'wallet: passive payout clamp missing');
assert.match(app, /Math\.max\(0, n - a\.price\)/, 'wallet: trade spend clamp missing');
const firstLogin = hydrateDailyProgress(DEFAULT_PROGRESSION, Date.UTC(2026, 0, 1));
const nextLogin = hydrateDailyProgress(firstLogin, Date.UTC(2026, 0, 2));
const missedLogin = hydrateDailyProgress(nextLogin, Date.UTC(2026, 0, 4));
assert.equal(firstLogin.loginStreak, 1, 'progression: first streak failed');
assert.equal(nextLogin.loginStreak, 2, 'progression: consecutive streak failed');
assert.equal(missedLogin.loginStreak, 1, 'progression: missed streak reset failed');
assert.match(app, /missionClaimed/, 'progression: mission state missing');
const ipoBusiness = { ...retail, hourlyNetProfit: 2000 };
assert.equal(getIPOEligibility({ ...ipoBusiness, isAcquired: false }, null).eligible, false, 'IPO: unacquired company was eligible');
assert.equal(getIPOEligibility(ipoBusiness, null).eligible, true, 'IPO: eligible company was blocked');
const listing = createIPOListing(ipoBusiness, Date.UTC(2026, 0, 1));
assert.equal(getIPOEligibility(ipoBusiness, listing).eligible, false, 'IPO: duplicate public offering was allowed');
assert.match(app, /requestPurchase/, 'purchase: request missing');
assert.match(app, /Purchase was not confirmed/, 'purchase: confirmation guard missing');
assert.match(app, /Purchase not completed/, 'purchase: failure path missing');
assert.match(app, /finishTransaction/, 'purchase: transaction finishing missing');
assert.ok(app.includes('SafeAreaView edges={["top", "bottom", "left", "right"]}'), 'safe area: root edges missing');
assert.ok(businessScreen.includes("SafeAreaView edges={['top', 'left', 'right']}"), 'safe area: business edges missing');
assert.match(app, /setInterval\(saveNow, 5000\)/, 'timers: save interval missing');
assert.match(app, /return \(\) => clearInterval\(timer\)/, 'timers: App cleanup missing');
assert.match(businessScreen, /return \(\) => clearInterval\(timer\)/, 'timers: business cleanup missing');
assert.match(registration, /clearTimeout\(incorporationTimer\.current\)/, 'timers: registration cleanup missing');
assert.match(network, /clearInterval\(timer\)/, 'timers: clock observer cleanup missing');
console.log('Round 2 baseline regression matrix passed');
